"""Desktop/mobile map interactions through file URLs, without a server."""
from pathlib import Path
from playwright.sync_api import sync_playwright,expect

ROOT=Path(__file__).resolve().parents[1];OUT=ROOT/'outputs/market-visuals/qa';OUT.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(channel='msedge',headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1050})
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto((ROOT/'_site/us-market.html').as_uri())
    expect(page.locator('.market-kpi')).to_have_count(3)
    page.locator('#market-map [data-state="MA"]').click()
    expect(page.locator('#market-detail')).to_contain_text('Massachusetts')
    expect(page.locator('#market-detail strong')).to_have_text('21')
    page.locator('#market-measure').select_option('analytics')
    expect(page.locator('#market-detail strong')).to_have_text('130')
    page.locator('#size-measure').select_option('workforce')
    expect(page.locator('#size-chart')).to_contain_text('140,758')
    page.locator('#employer-measure').select_option('analytics')
    expect(page.locator('#employer-chart')).to_contain_text('549')
    page.screenshot(path=str(OUT/'us-state.png'),full_page=True)
    page.locator('#market-layer').select_option('county')
    expect(page.locator('#market-map [data-county]')).to_have_count(3144)
    page.locator('#county-region').select_option('25')
    expect(page.locator('#market-map [data-county]')).to_have_count(14)
    page.locator('#county-pick').select_option('25025')
    expect(page.locator('#market-detail')).to_contain_text('Suffolk')
    expect(page.locator('#market-detail')).to_contain_text('2024')
    expect(page.locator('#market-detail')).to_contain_text('Quality:')
    page.locator('#market-map [data-county="25017"]').click()
    expect(page.locator('#county-pick')).to_have_value('25017')
    expect(page.locator('#market-detail')).to_contain_text('Middlesex')
    page.screenshot(path=str(OUT/'us-county.png'),full_page=True)
    page.locator('#county-region').select_option('all')
    # A missing estimate must stay missing when selected, not become a zero.
    missing=page.evaluate("window.MARKET_VISUALS.counties.find(c=>c.value===null).geoid")
    page.locator('#county-pick').select_option(missing)
    expect(page.locator('#market-detail strong')).to_have_text('No estimate')
    assert not errors,errors
    for name in ['us-market','boston-market']:
        page.goto((ROOT/'_site'/f'{name}.html').as_uri())
        if name=='boston-market':
            expect(page.locator('#market-layer')).to_have_value('county')
            expect(page.locator('#county-region')).to_have_value('25')
            expect(page.locator('#employer-chart')).to_contain_text('5,628')
            page.locator('#employer-measure').select_option('commercial')
            expect(page.locator('#employer-chart')).to_contain_text('Outside inventory')
        assert not page.locator('.market-evidence').evaluate('(e)=>e.open')
        page.screenshot(path=str(OUT/(name+'-desktop-top.png')))
        page.set_viewport_size({'width':390,'height':844})
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'), page.evaluate("[...document.querySelectorAll('main *,nav')].filter(e=>e.getBoundingClientRect().right>innerWidth+1).slice(0,15).map(e=>[e.tagName,e.id,e.className,e.getBoundingClientRect().width])")
        page.screenshot(path=str(OUT/(name+'-mobile-top.png')))
        page.locator('#market-layer').scroll_into_view_if_needed()
        page.screenshot(path=str(OUT/(name+'-mobile-map.png')))
        page.locator('.market-evidence summary').click()
        expect(page.locator('.market-evidence table').first).to_be_visible()
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'), page.evaluate("[...document.querySelectorAll('main *,nav')].filter(e=>e.getBoundingClientRect().right>innerWidth+1).slice(0,15).map(e=>[e.tagName,e.id,e.className,e.getBoundingClientRect().width])")
        page.set_viewport_size({'width':1440,'height':1050})
    assert not errors,errors
    browser.close()
print('MARKET_BROWSER_OK: state/county selection, metrics, quality, missing values, disclosures and mobile layout')
